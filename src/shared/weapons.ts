export interface WeaponSpec {
  id: WeaponId;
  name: string;
  shortName: string;
  category: WeaponCategory;
  caliber: string;
  actionStyle: WeaponActionStyle;
  slot: number;
  damage: number;
  pellets: number;
  headshotMultiplier: number;
  fireRate: number; // shots per second
  magSize: number;
  maxReserve: number;
  reloadTime: number; // seconds
  hipSpread: number;
  adsSpread: number;
  recoilPitch: number;
  recoilYaw: number;
  adsFov: number;
  adsSpeedMul: number;
  range: number;
  automatic: boolean;
  supportedFireModes: FireMode[];
  defaultFireMode: FireMode;
  tracerColor: number;
  hitEffectScale: number; // scales sparks, tracer size & knockback
  smokeIntensity: number; // scales muzzle smoke puffs
  soundRadius: number; // meters enemies can hear gunfire
  scopeStyle: ScopeStyle;
}

