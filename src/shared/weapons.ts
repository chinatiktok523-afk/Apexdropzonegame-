export type WeaponId =
  | 'unarmed'
  | 'pistol'
  | 'smg'
  | 'm4a1'
  | 'hk416'
  | 'hk416_cqb'
  | 'm27_iar'
  | 'm7'
  | 'xm8'
  | 'm16'
  | 'mk17'
  | 'mcx'
  | 'm249'
  | 'sniper'
  | 'shotgun'
  | 'rocket';

export type FireMode = 'auto' | 'burst' | 'semi';
export type ScopeStyle = 'reflex' | 'holo' | 'acog' | 'sniper' | 'ghostring' | 'launcher';
export type WeaponCategory =
  | 'Unarmed'
  | 'Sidearm'
  | 'SMG / PDW'
  | 'Assault Rifle'
  | 'Battle Rifle'
  | 'LMG'
  | 'Sniper'
  | 'Shotgun'
  | 'Launcher';
export type WeaponActionStyle = 'none' | 'slide' | 'auto_bolt' | 'bolt' | 'pump' | 'lmg' | 'launcher';

