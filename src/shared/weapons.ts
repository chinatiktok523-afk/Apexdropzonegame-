export function normalizeWeaponId(raw: unknown): WeaponId {
  if (raw === 'ak47') return 'm4a1';
  if (typeof raw === 'string' && raw in WEAPONS) {
    return raw as WeaponId;
  }
  return 'm4a1';
}

export function createWeaponRecord<T>(
  factory: (id: WeaponId, spec: WeaponSpec) => T,
): Record<WeaponId, T> {
  const rec = {} as Record<WeaponId, T>;
  for (const id of WEAPON_ORDER) {
    rec[id] = factory(id, WEAPONS[id]);
  }
  return rec;
}
